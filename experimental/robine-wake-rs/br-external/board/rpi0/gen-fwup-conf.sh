#!/bin/sh
# Generate fwup.conf for the Raspberry Pi Zero 1 W (OPS-001, PLT-005).
set -e

IMAGES=$1
BOARD_DIR=$2
RPI3_BOARD_DIR="$BOARD_DIR/../rpi3"

BOOT_FILES="
rpi-firmware/start.elf:start.elf
rpi-firmware/fixup.dat:fixup.dat
rpi-firmware/config.txt:config.txt
zImage:zImage
bcm2708-rpi-zero-w.dtb:bcm2708-rpi-zero-w.dtb
rpi-firmware/overlays/merus-amp.dtbo:overlays/merus-amp.dtbo
rpi-firmware/overlays/hifiberry-dacplus.dtbo:overlays/hifiberry-dacplus.dtbo
rpi-firmware/overlays/justboom-dac.dtbo:overlays/justboom-dac.dtbo
rpi-firmware/overlays/disable-bt.dtbo:overlays/disable-bt.dtbo
"

write_boot_files() {
	for entry in $BOOT_FILES; do
		target=${entry#*:}
		echo "    on-resource $target { fat_write(\${$1}, \"$target\") }"
	done
}

upgrade_task() {
	slot=$1
	other=$2
	SLOT=$(echo "$slot" | tr a-z A-Z)
	OTHER=$(echo "$other" | tr a-z A-Z)
	cat <<EOF

task upgrade.$slot {
    require-path-at-offset("/", \${ROOTFS_${OTHER}_PART_OFFSET})
    require-uboot-variable(uboot-env, "$other.robine_fw_validated", "1")
    require-uboot-variable(uboot-env, "$other.robine_fw_platform", "\${ROBINE_FW_PLATFORM}")
    require-uboot-variable(uboot-env, "$other.robine_fw_architecture", "\${ROBINE_FW_ARCHITECTURE}")

    on-init {
        info("Upgrading slot $slot")
        uboot_setenv(uboot-env, "$slot.robine_fw_validated", "0")
        uboot_unsetenv(uboot-env, "$slot.robine_fw_version")
        uboot_unsetenv(uboot-env, "$slot.robine_fw_platform")
        uboot_unsetenv(uboot-env, "$slot.robine_fw_architecture")
        uboot_unsetenv(uboot-env, "$slot.robine_fw_uuid")
        fat_mkfs(\${BOOT_${SLOT}_PART_OFFSET}, \${BOOT_${SLOT}_PART_COUNT})
        fat_setlabel(\${BOOT_${SLOT}_PART_OFFSET}, "BOOT-$SLOT")
        fat_mkdir(\${BOOT_${SLOT}_PART_OFFSET}, "overlays")
        trim(\${ROOTFS_${SLOT}_PART_OFFSET}, \${ROOTFS_${SLOT}_PART_COUNT})
    }

    on-resource cmdline-$slot.txt { fat_write(\${BOOT_${SLOT}_PART_OFFSET}, "cmdline.txt") }
$(write_boot_files "BOOT_${SLOT}_PART_OFFSET")
    on-resource rootfs.img { raw_write(\${ROOTFS_${SLOT}_PART_OFFSET}) }

    on-finish {
        uboot_setenv(uboot-env, "$slot.robine_fw_product", "\${ROBINE_FW_PRODUCT}")
        uboot_setenv(uboot-env, "$slot.robine_fw_version", "\${ROBINE_FW_VERSION}")
        uboot_setenv(uboot-env, "$slot.robine_fw_platform", "\${ROBINE_FW_PLATFORM}")
        uboot_setenv(uboot-env, "$slot.robine_fw_architecture", "\${ROBINE_FW_ARCHITECTURE}")
        uboot_setenv(uboot-env, "$slot.robine_fw_uuid", "\\\${FWUP_META_UUID}")
    }
}
EOF
}

cat <<EOF
# Generated by gen-fwup-conf.sh — do not edit.
require-fwup-version="1.16.0"
include("$BOARD_DIR/fwup-common.conf")

file-resource bootcode.bin { host-path = "$IMAGES/rpi-firmware/bootcode.bin" }
file-resource cmdline-a.txt { host-path = "$RPI3_BOARD_DIR/cmdline-a.txt" }
file-resource cmdline-b.txt { host-path = "$RPI3_BOARD_DIR/cmdline-b.txt" }
EOF
for entry in $BOOT_FILES; do
	echo "file-resource ${entry#*:} { host-path = \"$IMAGES/${entry%%:*}\" }"
done
cat <<EOF
file-resource rootfs.img {
    host-path = "$IMAGES/rootfs.squashfs"
    assert-size-lte = \${ROOTFS_A_PART_COUNT}
}

task complete {
    require-unmounted-destination = true

    on-init {
        mbr_write(mbr)

        fat_mkfs(\${AUTOBOOT_PART_OFFSET}, \${AUTOBOOT_PART_COUNT})
        fat_setlabel(\${AUTOBOOT_PART_OFFSET}, "AUTOBOOT")
        fat_mkfs(\${BOOT_A_PART_OFFSET}, \${BOOT_A_PART_COUNT})
        fat_setlabel(\${BOOT_A_PART_OFFSET}, "BOOT-A")
        fat_mkdir(\${BOOT_A_PART_OFFSET}, "overlays")

        uboot_clearenv(uboot-env)
        uboot_setenv(uboot-env, "robine_fw_devpath", "\${ROBINE_FW_DEVPATH}")
        uboot_setenv(uboot-env, "a.robine_fw_validated", "1")
        uboot_setenv(uboot-env, "a.robine_fw_product", "\${ROBINE_FW_PRODUCT}")
        uboot_setenv(uboot-env, "a.robine_fw_version", "\${ROBINE_FW_VERSION}")
        uboot_setenv(uboot-env, "a.robine_fw_platform", "\${ROBINE_FW_PLATFORM}")
        uboot_setenv(uboot-env, "a.robine_fw_architecture", "\${ROBINE_FW_ARCHITECTURE}")
        uboot_setenv(uboot-env, "a.robine_fw_uuid", "\\\${FWUP_META_UUID}")
    }

    on-resource autoboot-a.txt { fat_write(\${AUTOBOOT_PART_OFFSET}, "autoboot.txt") }
    on-resource bootcode.bin { fat_write(\${AUTOBOOT_PART_OFFSET}, "bootcode.bin") }
    on-resource cmdline-a.txt { fat_write(\${BOOT_A_PART_OFFSET}, "cmdline.txt") }
$(write_boot_files BOOT_A_PART_OFFSET)
    on-resource rootfs.img { raw_write(\${ROOTFS_A_PART_OFFSET}) }

    on-finish {
        raw_memset(\${BOOT_B_PART_OFFSET}, 256, 0xff)
        raw_memset(\${ROOTFS_B_PART_OFFSET}, 256, 0xff)
        raw_memset(\${APP_PART_OFFSET}, 256, 0xff)
    }
}
EOF
upgrade_task a b
upgrade_task b a
cat <<EOF

task upgrade.fail {
    on-init {
        error("Upgrade refused: the running slot is not validated or the platform does not match.")
    }
}
EOF
